const TOKEN =
  /('(?:''|[^'])*')|("(?:""|[^"])*")|(`(?:``|[^`])*`)|(\[[^\]]*\])|(--[^\n]*)|(\/\*[\s\S]*?\*\/)|([A-Za-z_][A-Za-z0-9_]*)/g;

/** Rewrite unquoted SQL keywords/types. Quoted idents, strings, and comments stay as-is. */
export const applyKeywordCasing = (
  sql: string,
  keyword: (word: string) => string,
): string =>
  sql.replace(TOKEN, (match, _s, _d, _b, _br, _lc, _bc, word) =>
    word !== undefined && SQL_KEYWORDS.has(word.toUpperCase())
      ? keyword(word)
      : match,
  );
